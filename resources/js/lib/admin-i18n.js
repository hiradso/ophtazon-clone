// چون فرانسه نباید پنل مدیریت را ترجمه کند، هر locale غیر از fa به en می‌افتد
export function at(key, locale) {
    const table = locale === "fa" ? adminTranslations.fa : adminTranslations.en;
    return table[key] ?? adminTranslations.en[key] ?? key;
}
